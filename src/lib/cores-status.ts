/** Converte cor do Elora App ("SKY_400", "GREEN") ou hex em hex; desconhecida = null. */
export function corParaHex(cor: unknown): string | null {
  const s = String(cor ?? "").trim();
  if (/^#[0-9a-f]{6}$/i.test(s)) return s.toLowerCase();
  if (/^#[0-9a-f]{3}$/i.test(s)) return ("#" + s.slice(1).split("").map((c) => c + c).join("")).toLowerCase();
  const m = /^([A-Za-z]+)(?:_(\d{2,3}))?$/.exec(s);
  const fam = m && FAMILIAS[m[1].toUpperCase()];
  if (!fam) return null;
  const alvo = m![2] ? Number(m![2]) : 500;
  const tons = Object.keys(fam).map(Number);
  const tom = tons.reduce((a, b) => (Math.abs(b - alvo) < Math.abs(a - alvo) ? b : a));
  return fam[tom];
}

function lum(hex: string) {
  const [r, g, b] = [1, 3, 5].map((i) => { const c = parseInt(hex.slice(i, i + 2), 16) / 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
const contraste = (a: string, b: string) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
/** Texto preto ou branco, o que der mais contraste com o fundo. */
export function textoSobre(fundo: string): string {
  return contraste(fundo, "#000000") >= contraste(fundo, "#ffffff") ? "#000000" : "#ffffff";
}
export function estiloCor(cor: string | undefined | null): { backgroundColor: string; color: string } | undefined {
  const h = corParaHex(cor);
  return h ? { backgroundColor: h, color: textoSobre(h) } : undefined;
}
